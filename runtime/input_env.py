#!/usr/bin/env python3
"""Verify a generated TPC-H input sidecar before any worker sees the input."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shlex


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path)
    parser.add_argument('input')
    parser.add_argument('power', type=int)
    parser.add_argument('columns', type=int)
    parser.add_argument('keys', type=int)
    parser.add_argument('dtype')
    parser.add_argument('distribution')
    args = parser.parse_args()
    root = args.root.resolve()
    relative = Path(args.input)
    if relative.is_absolute() or '..' in relative.parts or not re.fullmatch(r'[A-Za-z0-9_./-]+', args.input):
        parser.error('input must be a safe repository-relative path')
    path = (root / relative).resolve()
    if not path.is_relative_to(root):
        parser.error('input resolves outside the repository')
    metadata = json.loads(Path(str(path) + '.manifest.json').read_text(encoding='utf-8'))
    if metadata.get('generator') != 'datafedsort-tpch-input-v1':
        parser.error('input must be generated by data/generateData.py')
    config = metadata.get('config', {})
    expected = dict(exp_n=args.power, m=args.columns, k=args.keys,
                    dtype=args.dtype, dist=args.distribution)
    if any(config.get(key) != value for key, value in expected.items()):
        parser.error('input sidecar does not match the requested case configuration')
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    sha = digest.hexdigest()
    if sha != metadata.get('sha256'):
        parser.error('input hash differs from its TPC-H sidecar')
    if metadata.get('rows') != 1 << args.power or metadata.get('cols') != args.columns:
        parser.error('input sidecar has an unexpected shape')
    print('export FES_INPUT_SHA256=' + shlex.quote(sha))
    print('export FES_PUBLIC_BENCHMARK=1')
    # These switches preserve native method dispatch and post-sort oracle hooks.
    print('export FES_REVISION_BENCH=1')
    print('export FES_PUBLIC_TPCH_INPUT=1')


if __name__ == '__main__':
    main()
